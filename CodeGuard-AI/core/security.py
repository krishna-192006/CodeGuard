"""
CodeGuard AI - Security Utilities
Input validation, file extension checks, and sanitisation helpers.
"""
from __future__ import annotations
import os
from pathlib import Path
from config.settings import ALLOWED_EXTENSIONS, MAX_FILE_SIZE_KB


def validate_file_extension(filename: str) -> tuple[bool, str]:
    """Return (is_valid, error_message)."""
    ext = Path(filename).suffix.lower()
    if ext not in ALLOWED_EXTENSIONS:
        return False, f"File type '{ext}' is not supported. Allowed: {', '.join(ALLOWED_EXTENSIONS)}"
    return True, ""


def validate_file_size(content: bytes) -> tuple[bool, str]:
    """Check file size does not exceed the configured limit."""
    size_kb = len(content) / 1024
    if size_kb > MAX_FILE_SIZE_KB:
        return False, f"File size {size_kb:.1f} KB exceeds the maximum allowed {MAX_FILE_SIZE_KB} KB."
    return True, ""


def sanitise_code_for_display(code: str, max_chars: int = 100_000) -> str:
    """Truncate very long code strings to avoid UI overload."""
    if len(code) > max_chars:
        return code[:max_chars] + "\n\n# ... [truncated for display]"
    return code


def mask_potential_secrets(text: str) -> str:
    """Replace obvious credential patterns with redacted markers for logging."""
    import re
    patterns = [
        (r'(?:api_key|apikey|password|secret|token)\s*=\s*["\'][^"\']+["\']', '***REDACTED***'),
    ]
    for pattern, replacement in patterns:
        text = re.sub(pattern, replacement, text, flags=re.IGNORECASE)
    return text


